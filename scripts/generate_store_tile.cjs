'use strict';
// Original, unpublished store promo draft, deliberately separate from the ZIP.
// No ABEMA-owned logos, source images, fonts, or third-party dependencies.
const fs = require('node:fs');
const path = require('node:path');
const W = 440, H = 280;
const palette = [
  [13, 24, 42], [21, 46, 72], [29, 136, 171], [239, 252, 247],
  [255, 199, 102], [59, 95, 128], [28, 62, 89]
];

function rounded(x, y, left, top, width, height, radius) {
  const dx = Math.max(left + radius - x, 0, x - (left + width - radius));
  const dy = Math.max(top + radius - y, 0, y - (top + height - radius));
  return x >= left && x <= left + width && y >= top && y <= top + height &&
    dx * dx + dy * dy <= radius * radius;
}

function triangle(x, y, a, b, c) {
  const sign = (p, q, r) => (p[0] - r[0]) * (q[1] - r[1]) -
    (q[0] - r[0]) * (p[1] - r[1]);
  const p = [x, y], a1 = sign(p, a, b),
    a2 = sign(p, b, c), a3 = sign(p, c, a);
  return !((a1 < 0 || a2 < 0 || a3 < 0) && (a1 > 0 || a2 > 0 || a3 > 0));
}

function sample(x, y) {
  let value = 0;
  if (rounded(x, y, 14, 14, 412, 252, 25)) value = 1;
  if (rounded(x, y, 45, 46, 160, 152, 30) ||
      triangle(x, y, [74, 186], [64, 230], [111, 198])) value = 2;
  if (rounded(x, y, 84, 121, 22, 54, 6) ||
      rounded(x, y, 116, 95, 22, 80, 6) ||
      rounded(x, y, 149, 112, 22, 63, 6)) value = 3;
  if ((x - 179) ** 2 + (y - 88) ** 2 < 11 ** 2) value = 4;
  for (const [l, t, w, h] of [[244, 72, 149, 21], [244, 110, 118, 16],
    [244, 151, 149, 16], [244, 194, 105, 16]]) {
    if (rounded(x, y, l, t, w, h, 8)) value = t === 72 ? 3 : 5;
  }
  if (rounded(x, y, 373, 111, 20, 16, 7) ||
      rounded(x, y, 360, 194, 33, 16, 7)) value = 6;
  return value;
}
const be32 = n => [(n >>> 24) & 255, (n >>> 16) & 255,
  (n >>> 8) & 255, n & 255];
function crc32(bytes) {
  let c = 0xffffffff;
  for (const byte of bytes) {
    c ^= byte;
    for (let i = 0; i < 8; i++)
      c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  }
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const bytes = [...type].map(c => c.charCodeAt(0)).concat(data);
  return [...be32(data.length), ...bytes, ...be32(crc32(bytes))];
}

function generate() {
  const raw = [];
  for (let y = 0; y < H; y++) {
    raw.push(0);
    for (let x = 0; x < W; x++) raw.push(sample(x + .5, y + .5));
  }
  const compressed = [0x78, 0x01];
  for (let pos = 0; pos < raw.length; pos += 65535) {
    const length = Math.min(65535, raw.length - pos);
    compressed.push(pos + length === raw.length ? 1 : 0,
      length & 255, length >>> 8, (~length) & 255, ((~length) >>> 8) & 255);
    // Keep the PNG generated by plain Node without adding dependencies.
    compressed.push(...raw.slice(pos, pos + length));
  }
  let a = 1, b = 0;
  for (const value of raw) {
    a = (a + value) % 65521;
    b = (b + a) % 65521;
  }
  compressed.push(...be32(((b << 16) | a) >>> 0));
  return Buffer.from([137, 80, 78, 71, 13, 10, 26, 10,
    ...chunk('IHDR', [...be32(W), ...be32(H), 8, 3, 0, 0, 0]),
    ...chunk('PLTE', palette.flat()),
    ...chunk('IDAT', compressed),
    ...chunk('IEND', [])]);
}

function main() {
  const filename = path.resolve(__dirname, '../store-assets/promo-small.png');
  const expected = generate();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(filename) || !fs.readFileSync(filename).equals(expected))
      throw new Error('Store promo image does not match generated draft');
    process.stdout.write('Unpublished 440x280 promo image matches its source.\n');
  } else {
    fs.mkdirSync(path.dirname(filename), { recursive: true });
    fs.writeFileSync(filename, expected);
    process.stdout.write('Generated unpublished 440x280 promo image.\n');
  }
}
if (require.main === module) main();
module.exports = { generate };
